// Regenerates src/content/article-index.gen.ts from the article bodies in src/content/{tr,en}.
// Run after editing an article:  node scripts/gen-article-index.mjs
// Why: the full bodies (~150 KB) used to ship in the JS of every page because the footer and
// cards need titles/slugs. Now pages import only this small index; an article page loads its
// body in the route loader (and SSR inlines it), so the bodies never block other pages.
import { createJiti } from "jiti";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const jiti = createJiti(import.meta.url, { alias: { "@": root + "src" } });
const { TR } = await jiti.import(root + "src/content/articles-tr.ts");
const { EN } = await jiti.import(root + "src/content/articles-en.ts");
const { summarize } = await jiti.import(root + "src/content/word-count.ts");

const out = { tr: {}, en: {} };
for (const [lang, bodies] of [
  ["tr", TR],
  ["en", EN],
])
  for (const [id, b] of Object.entries(bodies)) out[lang][id] = summarize(b);

const src = `// GENERATED by scripts/gen-article-index.mjs, do not edit by hand.
// A test (src/test/content.test.ts) fails if this file is out of date with the article bodies.
import type { ArticleSummary } from "./types";

export const SUMMARIES: Record<"tr" | "en", Record<string, ArticleSummary>> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(root + "src/content/article-index.gen.ts", src);
console.log("wrote article-index.gen.ts", Object.keys(out.tr).length, Object.keys(out.en).length);
